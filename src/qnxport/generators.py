"""Generators: QNX build scaffold (qcc Makefile fragment, CMake toolchain files) and a CI workflow.

Everything generated here is a STARTING POINT. It was written from the public
QNX 8.0 documentation (qcc -V target names gcc_ntoaarch64le / gcc_ntox86_64)
and has not been run against a QNX SDP by the authors. Each file says so at the
top. Check variable names, tool names and paths against your SDP install.
"""

import os
import re
import textwrap
from typing import List, Tuple

from . import __version__
from .scanner import ScanResult, read_text, system_include

ARCHES = ("aarch64le", "x86_64")
NON_PRODUCT_DIRS = {"test", "tests", "testing", "example", "examples", "doc", "docs", "benchmark", "benchmarks",
                    "bench", "fuzz", "contrib", "tools", "samples"}
CXX_EXT = {".cc", ".cpp", ".cxx", ".c++"}

MAIN_RE = re.compile(r"^\s*(?:int|void)\s+main\s*\(", re.M)

BANNER = ("STARTER FILE generated by qnxport %s. Written from the public QNX 8.0 documentation; NOT run against a QNX SDP "
          "by the authors. Check every name and path against your installed SDP." % __version__)


def _banner(prefix: str = "# ") -> str:
    return "\n".join(prefix + ln for ln in textwrap.wrap(BANNER, 96))


def safe_name(name: str) -> str:
    n = re.sub(r"[^A-Za-z0-9_]+", "_", name).strip("_")
    return n or "app"


def _detect(res: ScanResult) -> Tuple[List[str], List[str], List[str], dict]:
    """Return (c_sources, cxx_sources, main_files, libs) from the scan root."""
    srcs, cxx, mains = [], [], []
    libs = {}
    root = res.root if os.path.isdir(res.root) else os.path.dirname(res.root)
    for rel in res.source_files:
        ext = os.path.splitext(rel)[1].lower()
        parts = set(rel.split("/")[:-1])
        text = read_text(os.path.join(root, rel)) if os.path.isdir(res.root) else read_text(res.root)
        if text is None:
            continue
        for line in text.split("\n"):
            inc = system_include(line)
            if not inc:
                continue
            if inc in ("sys/socket.h", "netinet/in.h", "arpa/inet.h", "netdb.h"):
                libs["socket"] = "BSD sockets (QNX: libsocket; verify in your SDP docs)"
            if inc == "sys/inotify.h":
                libs["fsnotify"] = "inotify (documented: libfsnotify, needs fsevmgr running on the target)"
        if ext in (".c", *CXX_EXT):
            if parts & NON_PRODUCT_DIRS:
                continue
            (cxx if ext in CXX_EXT else srcs).append(rel)
            if MAIN_RE.search(text):
                mains.append(rel)
    return srcs, cxx, mains, libs


def makefile_fragment(res: ScanResult, name: str = "app") -> str:
    srcs, cxx, mains, libs = _detect(res)
    name = safe_name(name)
    common_c = [s for s in srcs if s not in mains]
    common_cxx = [s for s in cxx if s not in mains]
    L: List[str] = []
    L.append(_banner())
    L.append("#")
    L.append("# Usage (after sourcing your SDP environment script, which sets QNX_HOST and QNX_TARGET):")
    L.append("#   make -f Makefile.qnx QNX_ARCH=aarch64le     # or QNX_ARCH=x86_64")
    L.append("#")
    L.append("# qcc selects the target with -V<compiler>_<target>, e.g. -Vgcc_ntoaarch64le or -Vgcc_ntox86_64")
    L.append("# (see 'qcc -V' for the list installed on your host).")
    L.append("")
    L.append("NAME      := %s" % name)
    L.append("QNX_ARCH ?= aarch64le")
    L.append("ifeq ($(filter $(QNX_ARCH),aarch64le x86_64),)")
    L.append("$(error QNX_ARCH must be aarch64le or x86_64, got '$(QNX_ARCH)')")
    L.append("endif")
    L.append("ifneq ($(MAKECMDGOALS),clean)")
    L.append("ifeq ($(QNX_TARGET),)")
    L.append("$(error QNX_TARGET is not set: source the SDP environment script (qnxsdp-env.sh) first)")
    L.append("endif")
    L.append("endif")
    L.append("")
    L.append("QCC_TARGET      := gcc_nto$(QNX_ARCH)")
    L.append("# C++ variant name: confirm with 'qcc -V' (the docs list gcc_nto<arch>_cxx and gcc_nto<arch>_gpp).")
    L.append("QCC_TARGET_CXX  ?= $(QCC_TARGET)_cxx")
    L.append("CC              := qcc -V$(QCC_TARGET)")
    L.append("CXX             := q++ -V$(QCC_TARGET_CXX)")
    L.append("BUILD_DIR       := build/qnx-$(QNX_ARCH)")
    L.append("")
    L.append("CPPFLAGS += -DQNXPORT=1")
    L.append("CFLAGS   += -Wall -O2 -g")
    L.append("CXXFLAGS += -Wall -O2 -g")
    L.append("# Detected from #include lines (see the qnxport report):")
    if libs:
        for lib, why in sorted(libs.items()):
            L.append("LDLIBS   += -l%s   # %s" % (lib, why))
    else:
        L.append("# (no extra libraries detected)")
    L.append("")
    L.append("# Heuristic: files under %s were left out." % "/".join(sorted(NON_PRODUCT_DIRS)))
    L.append("COMMON_C   := " + (" \\\n              ".join(common_c) if common_c else ""))
    L.append("COMMON_CXX := " + (" \\\n              ".join(common_cxx) if common_cxx else ""))
    L.append("COMMON_OBJ := $(COMMON_C:%.c=$(BUILD_DIR)/%.o) $(foreach f,$(COMMON_CXX),$(BUILD_DIR)/$(basename $(f)).o)")
    L.append("")
    if mains:
        L.append("# One program per file that defines main():")
        L.append("PROGRAMS := " + " ".join(safe_name(os.path.splitext(os.path.basename(m))[0]) if len(mains) > 1 else name for m in mains))
        L.append("")
        L.append(".PHONY: all clean")
        L.append("all: $(addprefix $(BUILD_DIR)/,$(PROGRAMS))")
        L.append("")
        for m in mains:
            prog = safe_name(os.path.splitext(os.path.basename(m))[0]) if len(mains) > 1 else name
            is_cxx = os.path.splitext(m)[1].lower() in CXX_EXT
            ld = "$(CXX)" if (is_cxx or common_cxx) else "$(CC)"
            obj = "$(BUILD_DIR)/%s.o" % os.path.splitext(m)[0]
            L.append("%s: %s $(COMMON_OBJ)" % ("$(BUILD_DIR)/" + prog, obj))
            L.append("\t%s $(LDFLAGS) -o $@ $^ $(LDLIBS)" % ld)
            L.append("")
    else:
        L.append("# No main() found: build a shared library.")
        L.append(".PHONY: all clean")
        L.append("all: $(BUILD_DIR)/lib$(NAME).so")
        L.append("")
        L.append("$(BUILD_DIR)/lib$(NAME).so: CFLAGS += -fPIC")
        L.append("$(BUILD_DIR)/lib$(NAME).so: CXXFLAGS += -fPIC")
        L.append("$(BUILD_DIR)/lib$(NAME).so: $(COMMON_OBJ)")
        L.append("\t%s -shared $(LDFLAGS) -o $@ $^ $(LDLIBS)" % ("$(CXX)" if common_cxx else "$(CC)"))
        L.append("")
    L.append("$(BUILD_DIR)/%.o: %.c")
    L.append("\t@mkdir -p $(@D)")
    L.append("\t$(CC) $(CPPFLAGS) $(CFLAGS) -MMD -MP -c -o $@ $<")
    L.append("")
    for ext in sorted(CXX_EXT):
        L.append("$(BUILD_DIR)/%%.o: %%%s" % ext)
        L.append("\t@mkdir -p $(@D)")
        L.append("\t$(CXX) $(CPPFLAGS) $(CXXFLAGS) -MMD -MP -c -o $@ $<")
        L.append("")
    L.append("clean:")
    L.append("\trm -rf build/qnx-aarch64le build/qnx-x86_64")
    L.append("")
    L.append("-include $(shell find $(BUILD_DIR) -name '*.d' 2>/dev/null)")
    L.append("")
    return "\n".join(L)


def cmake_toolchain(arch: str) -> str:
    assert arch in ARCHES
    proc = {"aarch64le": "aarch64", "x86_64": "x86_64"}[arch]
    return """# {banner}
#
# CMake toolchain file for QNX 8.0 ({arch}).
# Usage:  source <SDP>/qnxsdp-env.sh
#         cmake -S . -B build-qnx-{arch} -DCMAKE_TOOLCHAIN_FILE=qnx-toolchain-{arch}.cmake
#
# CMAKE_<LANG>_COMPILER_TARGET makes CMake add qcc's -V<target> option (CMake's QNX/QCC support;
# needs a reasonably recent CMake: verify with your version).
cmake_minimum_required(VERSION 3.16)

if(NOT DEFINED ENV{{QNX_HOST}} OR NOT DEFINED ENV{{QNX_TARGET}})
  message(FATAL_ERROR "QNX_HOST/QNX_TARGET are not set: source the QNX SDP environment script (qnxsdp-env.sh) first.")
endif()

set(QNX_ARCH {arch})
set(QNX_HOST   "$ENV{{QNX_HOST}}")
set(QNX_TARGET "$ENV{{QNX_TARGET}}")

set(CMAKE_SYSTEM_NAME      QNX)
set(CMAKE_SYSTEM_VERSION   8.0)
set(CMAKE_SYSTEM_PROCESSOR {proc})

if(CMAKE_HOST_WIN32)
  set(_exe_suffix ".exe")
else()
  set(_exe_suffix "")
endif()

set(CMAKE_C_COMPILER   "${{QNX_HOST}}/usr/bin/qcc${{_exe_suffix}}")
set(CMAKE_CXX_COMPILER "${{QNX_HOST}}/usr/bin/q++${{_exe_suffix}}")
set(CMAKE_C_COMPILER_TARGET   gcc_nto${{QNX_ARCH}})
# C++ variant: confirm the exact name with 'qcc -V' (docs list gcc_nto<arch>_cxx and gcc_nto<arch>_gpp).
set(CMAKE_CXX_COMPILER_TARGET gcc_nto${{QNX_ARCH}}_cxx)

# Binutils are prefixed nto<cpu>- in the SDP host tools (verify the names in ${{QNX_HOST}}/usr/bin).
set(CMAKE_AR     "${{QNX_HOST}}/usr/bin/nto{proc}-ar${{_exe_suffix}}"     CACHE FILEPATH "")
set(CMAKE_RANLIB "${{QNX_HOST}}/usr/bin/nto{proc}-ranlib${{_exe_suffix}}" CACHE FILEPATH "")

set(CMAKE_FIND_ROOT_PATH "${{QNX_TARGET}}" "${{QNX_TARGET}}/{arch}")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)

# Flags often needed when porting (see the qnxport report for the reasons):
#   add_compile_definitions(QNXPORT=1)
#   link BSD sockets:  target_link_libraries(<tgt> PRIVATE socket)
#   inotify users:     target_link_libraries(<tgt> PRIVATE fsnotify)
""".format(banner=_banner()[2:], arch=arch, proc=proc)


