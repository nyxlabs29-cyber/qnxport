def write_scaffold(res: ScanResult, outdir: str, name: str, arch: str = "both") -> List[str]:
    os.makedirs(outdir, exist_ok=True)
    written = []
    p = os.path.join(outdir, "Makefile.qnx")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(makefile_fragment(res, name))
    written.append(p)
    for a in (ARCHES if arch == "both" else (arch,)):
        p = os.path.join(outdir, "qnx-toolchain-%s.cmake" % a)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(cmake_toolchain(a))
        written.append(p)
    return written
